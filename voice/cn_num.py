"""中文数字口播 → 阿拉伯数字（一对一映射）

数值场景有限（温度 25-29、音量、分钟数），显式映射比通用解析脚本
更直观、更可测。映射外的中文数字保持原样，不强行转换。

注意：不要对原始 query 无脑替换——歌名里可能含"七里香"这类字样，
只在数字正则未命中时用它作二次匹配。
"""

from __future__ import annotations

CN_NUM_MAP: dict[str, str] = {
    # 温度 25-29 档（含点五）
    "二十五": "25", "二十五点五": "25.5",
    "二十六": "26", "二十六点五": "26.5",
    "二十七": "27", "二十七点五": "27.5",
    "二十八": "28", "二十八点五": "28.5",
    "二十九": "29", "二十九点五": "29.5",
    # 常用整十数（音量 / 分钟）
    "十": "10", "二十": "20", "三十": "30", "四十": "40", "五十": "50",
    "六十": "60", "七十": "70", "八十": "80", "九十": "90", "一百": "100",
    # 高频夹档
    "十五": "15", "十六": "16", "四十五": "45", "七十五": "75",
}

# 语序规范："二十七度半"这类口播先调成"二十七点五度"，再做数字映射
_PHRASE_FIX = (("度半", "点五度"), ("度五", "点五度"))


def cn_to_arabic(text: str) -> str:
    text = text.strip()
    for src, dst in _PHRASE_FIX:
        text = text.replace(src, dst)
    # 长 key 优先，避免"二十六点五"被"二十六"提前吃掉一半
    for cn in sorted(CN_NUM_MAP, key=len, reverse=True):
        if cn in text:
            text = text.replace(cn, CN_NUM_MAP[cn])
    return text
